DROP TABLE IF EXISTS order_items, orders, customers, staff, menu_items, categories;

CREATE TABLE categories (
  id   integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE menu_items (
  id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name        text NOT NULL UNIQUE,
  category_id integer NOT NULL REFERENCES categories (id),
  price       numeric(5, 2) NOT NULL CHECK (price > 0),
  vegetarian  boolean NOT NULL DEFAULT false,
  available   boolean NOT NULL DEFAULT true
);

CREATE TABLE staff (
  id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  first_name  text NOT NULL,
  last_name   text NOT NULL,
  role        text NOT NULL,
  hourly_rate numeric(5, 2) NOT NULL CHECK (hourly_rate > 0),
  started_on  date NOT NULL
);

CREATE TABLE customers (
  id        integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name      text NOT NULL,
  email     text UNIQUE,
  phone     text,
  joined_on date NOT NULL DEFAULT current_date
);

CREATE TABLE orders (
  id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ordered_at  timestamp NOT NULL,
  staff_id    integer NOT NULL REFERENCES staff (id),
  customer_id integer REFERENCES customers (id),
  payment     text NOT NULL CHECK (payment IN ('Card', 'Cash'))
);

CREATE TABLE order_items (
  order_id     integer NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  menu_item_id integer NOT NULL REFERENCES menu_items (id),
  quantity     integer NOT NULL CHECK (quantity > 0),
  unit_price   numeric(5, 2) NOT NULL CHECK (unit_price >= 0),
  PRIMARY KEY (order_id, menu_item_id)
);

